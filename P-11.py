# 1. Write a program to demonstrate conditional statements using if if-else and if-elif-else. 

age = 20

if age >= 18:
    print("You are eligible to vote.")

number = 10

if number % 2 == 0:
    print("Number is Even.")
else:
    print("Number is Odd.")

marks = 75

if marks >= 90:
    print("Grade: A+")
elif marks >= 75:
    print("Grade: A")
elif marks >= 60:
    print("Grade: B")
elif marks >= 50:
    print("Grade: C")
else:
    print("Grade: F")