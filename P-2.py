#2. Write a program to illustrate the use of different data types and type casting.
 
# Different data types
name = "Anant"         
age = 20                
height = 5.8            
is_student = True       

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student:", is_student)

# Type casting
num = "25"

integer_num = int(num)      
float_num = float(num)      
string_num = str(100)       

print("\nAfter Type Casting:")
print("Integer:", integer_num)
print("Float:", float_num)
print("String:", string_num)


print("\nData Types:")
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))